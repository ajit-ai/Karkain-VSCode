import * as assert from 'assert';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import {
  MANIFEST_FILE,
  describeProject,
  findProjectRoot,
  isProjectRoot,
  loadProject,
  manifestPath,
  parseManifest,
  readManifest,
} from '../../project';

function makeTree(): { root: string; sub: string; file: string } {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'karkain-proj-'));
  const sub = path.join(root, 'src');
  fs.mkdirSync(sub, { recursive: true });
  const file = path.join(sub, 'main.kark');
  // Same flat shape the real 1.1.0 `pkg init` emits (see fixtures/project).
  fs.writeFileSync(
    path.join(root, MANIFEST_FILE),
    'name = "sample"\nversion = "0.1.0"\nlicense = "MIT"\ntargets = ["native"]\n',
  );
  fs.writeFileSync(file, 'func main() { print("hi") }\n');
  return { root, sub, file };
}

describe('project', () => {
  describe('findProjectRoot', () => {
    it('finds the root from a nested file and directory', () => {
      const { root, sub, file } = makeTree();
      assert.strictEqual(findProjectRoot(file), root);
      assert.strictEqual(findProjectRoot(sub), root);
      assert.strictEqual(findProjectRoot(root), root);
      fs.rmSync(root, { recursive: true, force: true });
    });

    it('returns null outside a project or on missing paths', () => {
      const lonely = fs.mkdtempSync(path.join(os.tmpdir(), 'karkain-lonely-'));
      assert.strictEqual(findProjectRoot(lonely), null);
      assert.strictEqual(findProjectRoot(path.join(lonely, 'nope.kark')), null);
      fs.rmSync(lonely, { recursive: true, force: true });
    });

    it('ignores a karkain.toml directory masquerading as a manifest', () => {
      const root = fs.mkdtempSync(path.join(os.tmpdir(), 'karkain-fake-'));
      fs.mkdirSync(path.join(root, MANIFEST_FILE));
      assert.strictEqual(isProjectRoot(root), false);
      assert.strictEqual(findProjectRoot(root), null);
      fs.rmSync(root, { recursive: true, force: true });
    });
  });

  describe('manifestPath', () => {
    it('points at karkain.toml under the root', () => {
      assert.strictEqual(manifestPath('/proj'), path.join('/proj', MANIFEST_FILE));
    });
  });

  describe('parseManifest', () => {
    // The exact shape `karkain 1.1.0 pkg init` generates (see
    // fixtures/project/karkain.toml): flat keys, no [package] table.
    it('parses the verified 1.1.0 flat manifest', () => {
      const m = parseManifest(
        [
          '// Real project layout as generated by Karkain 1.1.0 `pkg init`',
          'name = "sample"',
          'version = "0.1.0"',
          'description = "A Karkain project"',
          'license = "MIT"',
          'targets = ["native"]',
        ].join('\n'),
      );
      assert.strictEqual(m.name, 'sample');
      assert.strictEqual(m.version, '0.1.0');
      assert.strictEqual(m.description, 'A Karkain project');
      assert.strictEqual(m.license, 'MIT');
      assert.deepStrictEqual(m.targets, ['native']);
      assert.deepStrictEqual(m.sections, []);
      assert.deepStrictEqual(m.extraKeys, []);
    });

    it('does not treat a // inside a string as a comment', () => {
      const m = parseManifest('homepage = "https://example.com/x"\nname = "n"\n');
      assert.strictEqual(m.extraKeys.includes('homepage'), true);
      assert.strictEqual(m.name, 'n');
      // The value must survive intact in extraKeys terms: homepage is unknown,
      // but nothing after the // was swallowed.
      assert.strictEqual(m.sections.length, 0);
    });

    it('strips // and # comments outside strings', () => {
      const m = parseManifest('name = "a" // trailing\nversion = "1" # trailing\n');
      assert.strictEqual(m.name, 'a');
      assert.strictEqual(m.version, '1');
    });

    it('parses a multi-line targets array', () => {
      const m = parseManifest('targets = [\n  "native",\n  "wasm32-wasi",\n]\n');
      assert.deepStrictEqual(m.targets, ['native', 'wasm32-wasi']);
      assert.deepStrictEqual(m.extraKeys, []);
    });

    it('parses an empty array as empty, not unread', () => {
      const m = parseManifest('targets = []\n');
      assert.deepStrictEqual(m.targets, []);
      assert.deepStrictEqual(m.extraKeys, []);
    });

    it('records a section header and never merges its keys', () => {
      const m = parseManifest('[package]\nname = "shadowed"\nversion = "9"\n');
      assert.deepStrictEqual(m.sections, ['package']);
      // Top-level model stays empty: the verified manifest is flat, so a table
      // is reported rather than believed.
      assert.strictEqual(m.name, undefined);
      assert.strictEqual(m.version, undefined);
    });

    it('records unmodelled keys instead of dropping them', () => {
      const m = parseManifest('name = "a"\nedition = "2024"\n');
      assert.strictEqual(m.name, 'a');
      assert.deepStrictEqual(m.extraKeys, ['edition']);
    });

    it('reports a wrongly-typed known key as unread rather than coercing it', () => {
      const m = parseManifest('name = 42\nversion = true\ntargets = 7\n');
      assert.strictEqual(m.name, undefined);
      assert.strictEqual(m.version, undefined);
      assert.deepStrictEqual(m.targets, []);
      assert.deepStrictEqual(m.extraKeys.sort(), ['name', 'targets', 'version']);
    });

    it('rejects a partially non-string array rather than half-believing it', () => {
      const m = parseManifest('targets = ["native", 5]\n');
      assert.deepStrictEqual(m.targets, []);
      assert.deepStrictEqual(m.extraKeys, ['targets']);
    });

    it('reports an array left unterminated at EOF as unread', () => {
      const m = parseManifest('targets = ["native"\n');
      assert.deepStrictEqual(m.targets, []);
      assert.deepStrictEqual(m.extraKeys, ['targets']);
    });

    it('handles CRLF, blank lines and basic escapes', () => {
      const m = parseManifest('name = "a\\tb"\r\n\r\nversion = "1"\r\n');
      assert.strictEqual(m.name, 'a\tb');
      assert.strictEqual(m.version, '1');
    });

    it('resolves duplicate top-level keys last-wins', () => {
      const m = parseManifest('name = "first"\nname = "second"\n');
      assert.strictEqual(m.name, 'second');
    });

    it('returns an empty model for empty or junk input rather than throwing', () => {
      for (const text of ['', '\n\n', 'not an assignment\n???']) {
        const m = parseManifest(text);
        assert.deepStrictEqual(m, { targets: [], extraKeys: [], sections: [] });
      }
    });
  });

  describe('readManifest / loadProject / describeProject', () => {
    it('parses the committed fixtures/project manifest (real 1.1.0 output)', () => {
      const fixture = path.join(__dirname, '..', '..', '..', 'fixtures', 'project', 'karkain.toml');
      const m = parseManifest(fs.readFileSync(fixture, 'utf8'));
      assert.strictEqual(m.name, 'sample');
      assert.strictEqual(m.version, '0.1.0');
      assert.strictEqual(m.license, 'MIT');
      assert.deepStrictEqual(m.targets, ['native']);
      assert.deepStrictEqual(m.sections, []);
      assert.deepStrictEqual(m.extraKeys, []);
    });

    it('reads a real manifest off disk', () => {
      const { root, sub } = makeTree();
      const m = readManifest(root);
      assert.strictEqual(m?.name, 'sample');
      assert.deepStrictEqual(m?.targets, ['native']);
      fs.rmSync(root, { recursive: true, force: true });
      void sub;
    });

    it('returns null when the manifest is absent or unreadable', () => {
      const lonely = fs.mkdtempSync(path.join(os.tmpdir(), 'karkain-nomanifest-'));
      assert.strictEqual(readManifest(lonely), null);
      assert.strictEqual(loadProject(lonely), null);
      fs.rmSync(lonely, { recursive: true, force: true });
    });

    it('resolves the project for a nested file', () => {
      const { root, file } = makeTree();
      const project = loadProject(file);
      assert.strictEqual(project?.root, root);
      assert.strictEqual(project?.manifest.name, 'sample');
      fs.rmSync(root, { recursive: true, force: true });
    });

    it('describes a project as name@version, or whichever is known', () => {
      assert.strictEqual(describeProject(parseManifest('name = "a"\nversion = "1"\n')), 'a@1');
      assert.strictEqual(describeProject(parseManifest('name = "a"\n')), 'a');
      assert.strictEqual(describeProject(parseManifest('version = "1"\n')), '1');
      assert.strictEqual(describeProject(parseManifest('')), undefined);
    });
  });
});
